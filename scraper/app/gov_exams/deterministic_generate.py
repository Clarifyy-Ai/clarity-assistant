def generate_synonym(seed: str, index: int) -> DeterministicQuestion:
    word, correct, *wrongs = _SYNONYM_PAIRS[_seed_int(seed, index) % len(_SYNONYM_PAIRS)]
    options = [correct, *wrongs]
    slot = _seed_int(seed, index + 3) % 4
    options[0], options[slot] = options[slot], options[0]
    # Ensure correct at slot
    if correct in options:
        cur = options.index(correct)
        options[cur], options[slot] = options[slot], correct
    return DeterministicQuestion(
        question_text=f'Choose the synonym of "{word}":',
        options=options[:4],
        correct_index=slot,
        subject="English Language",
        topic="Vocabulary",
        difficulty="EASY",
        explanation=f'Synonym of {word} is {correct}. {PRACTICE_DISCLAIMER}',
        question_type="synonym",
    )


