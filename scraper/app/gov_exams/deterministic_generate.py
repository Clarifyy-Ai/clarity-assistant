def generate_static_gk(seed: str, index: int) -> DeterministicQuestion:
    stem, correct, w1, w2, w3, source_ref = _GK_FACTS[_seed_int(seed, index) % len(_GK_FACTS)]
    options = [correct, w1, w2, w3]
    slot = _seed_int(seed, index + 7) % 4
    if correct in options:
        cur = options.index(correct)
        options[cur], options[slot] = options[slot], correct
    # Lightly vary stem with index so near-dup detection does not collapse all GK
    varied = f"{stem} (practice set {(_seed_int(seed, index) % 97) + 1})"
    return DeterministicQuestion(
        question_text=varied,
        options=options[:4],
        correct_index=slot,
        subject="General Awareness",
        topic="Static GK",
        difficulty="EASY",
        explanation=f"{correct}. {PRACTICE_DISCLAIMER}",
        question_type="static_gk",
        source_reference=source_ref,
        is_current_affairs=False,
    )


_GENERATORS = {
    "percentage": generate_percentage,
    "simple_arithmetic": generate_simple_arithmetic,
    "number_series": generate_number_series,
    "coding_decoding": generate_coding_decoding,
    "directions": generate_directions,
    "synonym": generate_synonym,
    "antonym": generate_antonym,
    "static_gk": generate_static_gk,
}


def types_for_section(section_code: str, section_name: str = "") -> tuple[ApprovedType, ...]:
    key = (section_code or "").strip().lower()
    if key in SECTION_TYPE_MAP:
        return SECTION_TYPE_MAP[key]
    name = (section_name or "").strip().lower()
    for needle, types in (
        ("quant", SECTION_TYPE_MAP["quant"]),
        ("reason", SECTION_TYPE_MAP["reasoning"]),
        ("english", SECTION_TYPE_MAP["english"]),
        ("aware", SECTION_TYPE_MAP["ga"]),
        ("general", SECTION_TYPE_MAP["ga"]),
    ):
        if needle in key or needle in name:
            return types
    return APPROVED_TYPES


def generate_practice_variants(
    *,
    count: int,
    seed: str,
    allowed_types: Sequence[ApprovedType] | None = None,
    section_code: str | None = None,
    section_name: str | None = None,
) -> list[DeterministicQuestion]:
    """Generate up to `count` labeled practice variants for approved types only."""
    if count <= 0:
        return []
    if allowed_types:
        types = [t for t in allowed_types if t in APPROVED_TYPES]
    elif section_code or section_name:
        types = list(types_for_section(section_code or "", section_name or ""))
    else:
        types = list(APPROVED_TYPES)
    if not types:
        return []

    out: list[DeterministicQuestion] = []
    for i in range(count):
        qtype = types[i % len(types)]
        out.append(_GENERATORS[qtype](seed, i))
    return out
